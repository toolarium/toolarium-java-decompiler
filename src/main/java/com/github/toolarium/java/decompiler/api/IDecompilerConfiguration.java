package com.github.toolarium.java.decompiler.api;


/**
 * Configuration interface for controlling decompiler behavior.
 * Provides getters for all decompiler options covering output formatting,
 * decompilation feature toggles, filtering, and error handling.
 *
 * <p>Use {@link DecompilerConfigurationBuilder} to create instances with a fluent API,
 * or load from a properties file.
 *
 * @author patrick
 */
public interface IDecompilerConfiguration {

    /**
     * Get the indentation string used for each level of nesting.
     *
     * @return the indent string (default: four spaces)
     */
    String getIndentString();


    /**
     * Get the line separator used in emitted source code.
     *
     * @return the line separator (default: "\n")
     */
    String getLineSeparator();


    /**
     * Whether to emit a banner comment at the top of each decompiled file.
     * The banner reads: "// Decompiled by toolarium-java-decompiler".
     *
     * @return true if the banner should be shown (default: false)
     */
    boolean isShowBanner();


    /**
     * Whether to emit a source file comment showing the original file name.
     * The comment reads: "// Source: ClassName.java".
     *
     * @return true if the source file comment should be shown (default: false)
     */
    boolean isShowSourceFile();


    /**
     * Whether to remove bridge methods from the decompiled output.
     * Bridge methods are generated by the compiler for generic type erasure.
     *
     * @return true if bridge methods should be removed (default: true)
     */
    boolean isRemoveBridgeMethods();


    /**
     * Whether to remove synthetic members from the decompiled output.
     * Synthetic members are generated by the compiler for access to private members,
     * inner class references, and other internal purposes.
     *
     * @return true if synthetic members should be removed (default: true)
     */
    boolean isRemoveSyntheticMembers();


    /**
     * Whether to reconstruct assert statements from the compiler-generated
     * $assertionsDisabled pattern.
     *
     * @return true if assert reconstruction is enabled (default: true)
     */
    boolean isReconstructAssert();


    /**
     * Whether to reconstruct enum declarations from compiler-generated patterns.
     *
     * @return true if enum reconstruction is enabled (default: true)
     */
    boolean isReconstructEnum();


    /**
     * Whether to reconstruct inner classes by nesting them inside their
     * enclosing class during batch decompilation.
     *
     * @return true if inner class reconstruction is enabled (default: true)
     */
    boolean isReconstructInnerClasses();


    /**
     * Whether to reconstruct lambda expressions from invokedynamic/LambdaMetafactory
     * patterns and inline lambda method bodies.
     *
     * @return true if lambda reconstruction is enabled (default: true)
     */
    boolean isReconstructLambda();


    /**
     * Whether to reconstruct try-with-resources statements from compiler-generated
     * close()/addSuppressed() patterns.
     *
     * @return true if try-with-resources reconstruction is enabled (default: true)
     */
    boolean isReconstructTryWithResources();


    /**
     * Whether to reconstruct string switch statements from the two-phase
     * hashCode()/equals() pattern generated by the compiler.
     *
     * @return true if string switch reconstruction is enabled (default: true)
     */
    boolean isReconstructStringSwitch();


    /**
     * Whether to reconstruct record declarations from compiler-generated patterns.
     *
     * @return true if record reconstruction is enabled (default: true)
     */
    boolean isReconstructRecord();


    /**
     * Whether to reconstruct text blocks from multi-line string literals.
     * When enabled, strings containing newline characters are emitted as
     * text blocks using triple-quote syntax.
     *
     * @return true if text block reconstruction is enabled (default: true)
     */
    boolean isReconstructTextBlocks();


    /**
     * Whether to hide the default constructor when it has an empty body.
     * The default constructor is the no-argument constructor that calls super().
     *
     * @return true if empty default constructors should be hidden (default: true)
     */
    boolean isHideDefaultConstructor();


    /**
     * Whether to hide empty super() calls in constructors.
     * An empty super() call is redundant when the superclass is java.lang.Object.
     *
     * @return true if empty super() calls should be hidden (default: true)
     */
    boolean isHideEmptySuper();


    /**
     * Whether to add @Override annotations on methods that override a superclass
     * or implement an interface method.
     *
     * @return true if @Override annotations should be added (default: false)
     */
    boolean isShowOverrideAnnotation();


    /**
     * Get the regular expression pattern for including classes during batch decompilation.
     * Only classes whose fully qualified name matches this pattern will be decompiled.
     * A null value means all classes are included.
     *
     * @return the include regex, or null for no filter
     */
    String getIncludeClassRegex();


    /**
     * Get the regular expression pattern for excluding classes during batch decompilation.
     * Classes whose fully qualified name matches this pattern will be skipped.
     * A null value means no classes are excluded.
     *
     * @return the exclude regex, or null for no filter
     */
    String getExcludeClassRegex();


    /**
     * Whether to continue decompilation when invalid bytecode is encountered.
     * When enabled, methods with invalid bytecode produce a comment with the error
     * instead of failing the entire class.
     *
     * @return true if invalid bytecode should be ignored (default: false)
     */
    boolean isIgnoreInvalidBytecode();


    /**
     * Get the maximum time in seconds allowed for decompiling a single method.
     * A value of 0 means no time limit. When a method exceeds this limit,
     * a comment with the timeout is emitted instead of the method body.
     *
     * @return the maximum method decompilation time in seconds (default: 0)
     */
    int getMaxMethodTimeSeconds();
}
